def get_article(slug):
    # Ищем статью по её адресу. Если не нашли — None
    for article in ARTICLES:
        if article["slug"] == slug:
            return article
    return None


def articles_in_category(category):
    return [a for a in ARTICLES if a["category"] == category]


def article_of_the_day(day, category=None):
    # Каждый день своя статья, но весь день одна и та же.
    # Если указана категория, выбираем только из неё
    items = articles_in_category(category) if category else ARTICLES
    return items[day.toordinal() % len(items)]


def stem(word):
    # Отрезаем окончание: «айфоны» → «айфон». Короткие слова не трогаем
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[: -len(ending)]
    return word


def alias(word):
    # «айфон» → «iphone». Пока слово недописано («айф»), подходит и начало ключа
    if word in SEARCH_ALIASES:
        return SEARCH_ALIASES[word]
    if len(word) >= 3:
        for key, value in SEARCH_ALIASES.items():
            if key.startswith(word):
                return value
    return word


def query_words(query):
    # Слова запроса без окончаний, с заменой русских написаний: «айфоны про» → ["iphone", "pro"]
    return [alias(stem(w)) for w in query.lower().replace("ё", "е").split()]


def suggest_articles(query, limit=8):
    # Подсказки при вводе: выше те статьи, в названии которых больше слов запроса,
    # а среди них — где название совпадает с запросом или начинается с него
    words = query_words(query)

    def rank(a):
        title = a["title"].lower().replace("ё", "е")
        in_title = sum(w in title for w in words)
        exact = title == " ".join(words)
        return (-in_title, not exact, not title.startswith(words[0]))

    return sorted(search_articles(query), key=rank)[:limit]


def search_articles(query):
    # Ищем каждое слово запроса в заголовке, описании, фактах и тексте, без учёта регистра.
    # Статья подходит, только если в ней нашлись все слова
    # «ё» и «е» считаем одной буквой: «Тернус» найдёт «Тёрнус»
    words = query_words(query)
    if not words:
        return []

    results = []
    for article in ARTICLES:
        title = article["title"].lower()
        parts = [title, article["summary"], *article["facts"].values(), *article["body"]]
        for section in article.get("sections", []):
            parts += [section["title"], *section.get("paragraphs", []), *section.get("list", [])]
        text = " ".join(parts).lower().replace("ё", "е")
        if all(w in text for w in words):
            results.append(article)

    # Сначала статьи, где слово есть прямо в заголовке
    results.sort(key=lambda a: not any(w in a["title"].lower().replace("ё", "е") for w in words))
    return results
